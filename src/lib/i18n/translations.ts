export const dictionaries = { en, de } satisfies Record<Locale, Dict>;

/** `en` is written with literal string types (via `as const`) so typos are
 * easy to spot while authoring it. For the shared *shape* every locale must
 * match, those literals are irrelevant and actively unhelpful — `de` isn't
 * "assignable to the English sentence", it just needs a string in the same
 * place — so `Dict` widens every leaf string to `string` before it's used
 * as the type both dictionaries (and the key-path type below) are built from. */
type Widen<T> = T extends string ? string : { [K in keyof T]: Widen<T[K]> };
type Dict = Widen<typeof en>;

/** Every valid dotted translation key, e.g. "status.DIRTY" — computed from
 * the dictionary shape so a typo or a missing key is a compile-time error. */
type Join<K extends string | number, P extends string> = P extends "" ? `${K}` : `${K}.${P}`;
type Paths<T> = T extends string
  ? ""
  : { [K in keyof T & (string | number)]: Join<K, Paths<T[K]>> }[keyof T & (string | number)];
export type TKey = Paths<Dict>;

function getPath(obj: unknown, path: string): unknown {
  return path.split(".").reduce<unknown>((o, k) => (o && typeof o === "object" ? (o as Record<string, unknown>)[k] : undefined), obj);
}

/** Looks up `key` in `locale`'s dictionary and interpolates `{{var}}` placeholders. */
export function translate(locale: Locale, key: TKey, vars?: Record<string, string | number>): string {
  const raw = getPath(dictionaries[locale], key);
  let str = typeof raw === "string" ? raw : key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{{${k}}}`).join(String(v));
    }
  }
  return str;
}
